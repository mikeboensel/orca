import { createHash } from 'node:crypto'
import { basename, join } from 'node:path'
import { isPlainObject } from '../../shared/agent-memory/agent-memory-document-format'
import type {
  AgentMemoryRenderedFile,
  AgentMemoryRenderedScope
} from '../../shared/agent-memory/agent-memory-sync-types'
import {
  isAgentMemoryAgent,
  type AgentMemoryAgent
} from '../../shared/agent-memory/agent-memory-types'
import type { AgentMemoryFileChangeBatch } from './agent-memory-file-change-batch'
import { readTextFileOrNull, writeTextFileAtomically } from './agent-memory-file-io'

/** A memory the user shared, with the agents it is shared to. */
export type AgentMemorySharedEntry = {
  title: string
  description: string
  text: string
  agents: AgentMemoryAgent[]
}

export type AgentMemoryRenderedManifestEntry = AgentMemoryRenderedFile & {
  /** Agents with at least one memory in this file; their link blocks point here. */
  agents: AgentMemoryAgent[]
}

const AGENT_DISPLAY_NAMES: Record<AgentMemoryAgent, string> = {
  claude: 'Claude Code',
  codex: 'Codex',
  gemini: 'Gemini CLI',
  opencode: 'OpenCode',
  pi: 'Pi'
}

function renderedDirectory(storeRootDirectory: string): string {
  return join(storeRootDirectory, 'rendered')
}

function manifestPath(storeRootDirectory: string): string {
  return join(renderedDirectory(storeRootDirectory), 'manifest.json')
}

function scopeKey(scope: AgentMemoryRenderedScope): string {
  return scope.kind === 'global' ? 'global' : `repo:${scope.repoPath}`
}

/** Readable slug plus a short path hash, so two checkouts named alike never collide. */
export function agentMemoryRenderedPath(
  storeRootDirectory: string,
  scope: AgentMemoryRenderedScope
): string {
  if (scope.kind === 'global') {
    return join(renderedDirectory(storeRootDirectory), 'global.md')
  }
  const slug =
    basename(scope.repoPath)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'repo'
  const hash = createHash('sha256').update(scope.repoPath).digest('hex').slice(0, 8)
  return join(renderedDirectory(storeRootDirectory), 'repos', `${slug}-${hash}.md`)
}

function renderEntry(entry: AgentMemorySharedEntry): string {
  const lines = [`### ${entry.title}`]
  if (entry.description) {
    lines.push(`> ${entry.description}`)
  }
  if (entry.text) {
    lines.push('', entry.text)
  }
  return lines.join('\n')
}

export function renderAgentMemoryScopeFile(
  scope: AgentMemoryRenderedScope,
  entries: readonly AgentMemorySharedEntry[]
): string {
  const sections = [
    '<!-- Generated by Orca from memories shared in its Memory panel; edits here are overwritten. -->',
    scope.kind === 'global'
      ? '# Shared agent memories (every project)'
      : `# Shared agent memories for ${scope.repoPath} and its worktrees`
  ]
  const agents = [...new Set(entries.flatMap((entry) => entry.agents))]
  const everyone = entries.filter((entry) => agents.every((agent) => entry.agents.includes(agent)))
  sections.push(...everyone.map(renderEntry))
  for (const agent of agents) {
    const only = entries.filter(
      (entry) => !everyone.includes(entry) && entry.agents.includes(agent)
    )
    if (only.length > 0) {
      sections.push(`## Only for ${AGENT_DISPLAY_NAMES[agent]}`, ...only.map(renderEntry))
    }
  }
  return `${sections.join('\n\n')}\n`
}

export async function readRenderedManifest(
  storeRootDirectory: string
): Promise<AgentMemoryRenderedManifestEntry[]> {
  return parseManifest(await readTextFileOrNull(manifestPath(storeRootDirectory)))
}

function parseManifest(text: string | null): AgentMemoryRenderedManifestEntry[] {
  let parsed: unknown
  try {
    parsed = text ? JSON.parse(text) : []
  } catch {
    return []
  }
  if (!Array.isArray(parsed)) {
    return []
  }
  return parsed.flatMap((value: unknown) => {
    if (!isPlainObject(value) || !isPlainObject(value.scope) || typeof value.path !== 'string') {
      return []
    }
    const scope: AgentMemoryRenderedScope | null =
      value.scope.kind === 'global'
        ? { kind: 'global' }
        : value.scope.kind === 'repo' && typeof value.scope.repoPath === 'string'
          ? { kind: 'repo', repoPath: value.scope.repoPath }
          : null
    if (!scope) {
      return []
    }
    return [
      {
        scope,
        path: value.path,
        memoryCount: typeof value.memoryCount === 'number' ? value.memoryCount : 0,
        approximateTokens:
          typeof value.approximateTokens === 'number' ? value.approximateTokens : 0,
        agents: Array.isArray(value.agents) ? value.agents.filter(isAgentMemoryAgent) : []
      }
    ]
  })
}

/** Plans one scope's Orca-owned file (deleted when nothing is shared) and returns the next manifest. */
export async function planRenderedScope(
  batch: AgentMemoryFileChangeBatch,
  storeRootDirectory: string,
  scope: AgentMemoryRenderedScope,
  entries: readonly AgentMemorySharedEntry[]
): Promise<AgentMemoryRenderedManifestEntry[]> {
  const path = agentMemoryRenderedPath(storeRootDirectory, scope)
  const manifest = (await readRenderedManifest(storeRootDirectory)).filter(
    (entry) => scopeKey(entry.scope) !== scopeKey(scope)
  )
  if (entries.length === 0) {
    await batch.write(path, null, 'orca')
  } else {
    const text = renderAgentMemoryScopeFile(scope, entries)
    await batch.write(path, text, 'orca')
    manifest.push({
      scope,
      path,
      memoryCount: entries.length,
      approximateTokens: Math.ceil(text.length / 4),
      agents: [...new Set(entries.flatMap((entry) => entry.agents))].sort()
    })
  }
  manifest.sort((a, b) => scopeKey(a.scope).localeCompare(scopeKey(b.scope)))
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`
  const currentManifest = await batch.read(manifestPath(storeRootDirectory))
  // An unchanged manifest written in another key order is not a change worth previewing.
  if (JSON.stringify(parseManifest(currentManifest)) !== JSON.stringify(manifest)) {
    await batch.write(manifestPath(storeRootDirectory), manifestText, 'orca')
  }
  return manifest
}

export async function writeRenderedManifest(
  storeRootDirectory: string,
  manifest: readonly AgentMemoryRenderedManifestEntry[]
): Promise<void> {
  await writeTextFileAtomically(
    manifestPath(storeRootDirectory),
    `${JSON.stringify(manifest, null, 2)}\n`
  )
}
